// The wiraicon set: which icons it has, what they are called and where each one's drawing comes from.
// Chosen from what the team's apps use (PrimeIcons and Font Awesome names, counted across 29 apps) plus the icons a
// business app reaches for. Drawings come from Phosphor Icons (MIT), in five weights.
//
// [name, phosphor, aliases, category, weight]
// - name: the main class / component name (`wi wi-<name>`), following the names the team already writes.
// - phosphor: the Phosphor drawing.
// - aliases: other names that give the same icon (Font Awesome and Phosphor spellings, older names).
// - weight: set when the name itself means a weight, e.g. `star-fill` is always the filled star.

