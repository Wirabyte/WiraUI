import { FamilyId, SEMANTIC_KEYS } from './catalog';
import type { TokenMap } from './tokens';

/**
 * The look of each family as token values. Values only reference other tokens through var(), so the
 * primary/surface palettes, radius, density, shadows and focus style chosen in the config flow through.
 * Numbers follow the MIT-licensed themes each look is modelled on (DESIGN.md §6.10), so migrating apps keep their layout:
 * sila-classic / arun / material-classic = the classic theme.css look, mali / sila / material / phet = the styled presets.
 */
export interface FamilyTokens {
  light: TokenMap;
  dark: TokenMap;
}

const v = (name: string) => `var(--wt-${name})`;
const s = (n: number) => v(`surface-${n}`);
const p = (n: number) => v(`primary-${n}`);
/** Paddings scale with the density knob. */
const pad = (rem: string) => `calc(${rem} * var(--wt-density))`;
const tint = (ref: string, pct: number) => `color-mix(in srgb, ${ref} ${pct}%, transparent)`;
const WHITE_87 = 'rgba(255, 255, 255, 0.87)';

/** Shades per status colour: [solid, hover, active, soft background, soft text]. The dark soft background is a 16% tint of its shade. */
function severities(light: [number, number, number, number, number], dark: [number, number, number, number, number]): FamilyTokens {
  const l: TokenMap = {};
  const d: TokenMap = {};
  for (const k of SEMANTIC_KEYS) {
    l[`${k}-color`] = v(`${k}-${light[0]}`);
    l[`${k}-hover`] = v(`${k}-${light[1]}`);
    l[`${k}-active`] = v(`${k}-${light[2]}`);
    l[`${k}-bg`] = v(`${k}-${light[3]}`);
    l[`${k}-text`] = v(`${k}-${light[4]}`);
    d[`${k}-color`] = v(`${k}-${dark[0]}`);
    d[`${k}-hover`] = v(`${k}-${dark[1]}`);
    d[`${k}-active`] = v(`${k}-${dark[2]}`);
    d[`${k}-bg`] = tint(v(`${k}-${dark[3]}`), 16);
    d[`${k}-text`] = v(`${k}-${dark[4]}`);
  }
  return { light: l, dark: d };
}

/** The classic and styled looks put white text on every solid button; dark schemes use a dark text instead. */
function whiteOnColor(darkText: string): FamilyTokens {
  const l: TokenMap = { 'primary-contrast': '#ffffff' };
  const d: TokenMap = { 'primary-contrast': darkText };
  for (const k of SEMANTIC_KEYS) {
    l[`${k}-contrast`] = '#ffffff';
    d[`${k}-contrast`] = darkText;
  }
  return { light: l, dark: d };
}

const mix = (a: string, pct: number, b: string) => `color-mix(in srgb, ${a} ${pct}%, ${b})`;

