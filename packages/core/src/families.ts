function merge(...parts: FamilyTokens[]): FamilyTokens {
  const out: FamilyTokens = { light: {}, dark: {} };
  for (const part of parts) {
    Object.assign(out.light, part.light);
    Object.assign(out.dark, part.dark);
  }
  return out;
}

