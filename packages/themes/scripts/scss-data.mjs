// Renders scss/_data.scss from a @wiraui/core module object. Used by gen-scss-data.mjs
// and by the parity test (which checks the committed file is current).

const kebab = (s) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());

// String keys are quoted: a bare `gray` or `red` would be a Sass colour, not a name.
function key(k) {
  return /^\d+$/.test(k) ? k : `'${kebab(k)}'`;
}
// Token names are already kebab-case and may start with `--`; only quote them.
const raw = (k) => `'${k}'`;

function value(v) {
  if (typeof v === 'string') return `'${v.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (Array.isArray(v)) return `(${v.map(value).join(', ')})`;
  const keys = Object.keys(v);
  // `()` is Sass's empty map; `(a: b)` needs no trailing comma.
  if (!keys.length) return '()';
  return `(${keys.map((k) => `${key(k)}: ${value(v[k])}`).join(', ')})`;
}

/** A token map, one entry per line, keys exactly as core writes them. */
function tokenMap(map, indent) {
  const keys = Object.keys(map);
  if (!keys.length) return '()';
  return `(\n${keys.map((k) => `${indent}  ${raw(k)}: ${value(map[k])},`).join('\n')}\n${indent})`;
}
const lightDark = (t, indent) => `(\n${indent}  light: ${tokenMap(t.light, indent + '  ')},\n${indent}  dark: ${tokenMap(t.dark, indent + '  ')},\n${indent})`;

/** One entry per line so diffs of the generated file stay readable. */
function block(name, entries) {
  return `$${name}: (\n${entries.map((e) => `  ${e},`).join('\n')}\n);`;
}

function mapBlock(name, obj) {
  return block(
    name,
    Object.keys(obj).map((k) => `${key(k)}: ${value(obj[k])}`)
  );
}

const percents = (table) => Object.fromEntries(Object.keys(table).map((k) => [k, Math.round(table[k] * 100)]));

export function renderScssData(core) {
  const out = [
    '// Generated by scripts/gen-scss-data.mjs from @wiraui/core (catalog.ts, color.ts, families.ts, compat.ts, tokens.ts).',
    '// Do not edit by hand: change core, rebuild it, then run `pnpm --filter @wiraui/themes gen`.',
    '',
    `$shades: ${value([...core.SHADES])};`,
    '// Whole percents of white (tint) or black (shade-mix) mixed into the base colour, as mix() rounds them.',
    `$tint: ${value(percents(core.TINT))};`,
    `$shade-mix: ${value(percents(core.SHADE_MIX))};`,
    '',
    `$semantic-keys: ${value([...core.SEMANTIC_KEYS])};`,
    '',
    block(
      'primary-swatches',
      core.PRIMARY_SWATCHES.map((s) => `${key(s.id)}: ${value(s.hex)}`)
    ),
    '',
    '// Index 1 is shade 50, index 11 is shade 950.',
    mapBlock('surfaces', core.SURFACES),
    '',
    mapBlock('density', core.DENSITY),
    '',
    mapBlock('shadows', core.SHADOWS),
    '',
    `$focus-styles: ${value([...core.FOCUS_STYLES])};`,
    '',
    mapBlock('presets', core.PRESETS),
    '',
    '// sila-light-teal & co.: a preset plus primary / surface / scheme.',
    mapBlock('classic-themes', core.CLASSIC_THEMES),
    '',
    mapBlock('family-generation', core.FAMILY_GENERATION),
    '',
    '// Look of each family (families.ts).',
    block(
      'families',
      Object.keys(core.FAMILIES).map((f) => `${raw(f)}: ${lightDark(core.FAMILIES[f], '  ')}`)
    ),
    '',
    '// focusTokens() for each focus style.',
    block(
      'focus',
      core.FOCUS_STYLES.map((m) => `${raw(m)}: ${lightDark(core.focusTokens(m), '  ')}`)
    ),
    '',
    '// materialTokens() for each material.',
    block(
      'materials',
      ['solid', 'glass'].map((m) => `${raw(m)}: ${lightDark(core.materialTokens(m), '  ')}`)
    ),
    '',
    '// Classic/styled theme variables re-created per generation (compat.ts); emitted as written, without --wu-.',
    block(
      'compat',
      ['classic', 'styled', 'wira'].map((g) => `${raw(g)}: ${tokenMap(core.compatAliases(g), '  ')}`)
    ),
    '',
    '// Tokens that read a styled-mode --p-* variable first in the styled presets.',
    `$styled-inputs: ${tokenMap(core.STYLED_INPUTS, '')};`,
    '',
    '// Same order as COMPONENT_TOKENS; `key` is the kebab-case name used in $components.',
    block(
      'component-tokens',
      core.COMPONENT_TOKENS.map((s) => value({ id: s.id, key: kebab(s.key), camel: s.key, css: s.css, type: s.type }))
    ),
  ];
  return out.join('\n') + '\n';
}

/** utils/_palettes.scss: fixed colour palettes for text-blue-500, bg-green-100 … (shades 50–900). */
export function renderUtilsPalettes(core) {
  const entries = Object.keys(core.PALETTE_BASES).map((name) => {
    const p = core.generatePalette(core.PALETTE_BASES[name]);
    const shades = core.SHADES.filter((s) => s !== 950).map((s) => `${s}: ${value(p[s])}`);
    return `${key(name)}: (${shades.join(', ')})`;
  });
  return [
    '// Generated by scripts/gen-scss-data.mjs from @wiraui/core (compat.ts PALETTE_BASES, color.ts).',
    '// Do not edit by hand: change core, rebuild it, then run `pnpm --filter @wiraui/themes gen`.',
    '',
    block('palettes', entries),
  ].join('\n') + '\n';
}
