// Assembles packages/angular-<v>/lib from the shared sources (DESIGN.md §4):
//   core/            ← packages/core/src            (as the `wiraui/core` entry point)
//   config, presets, component modules/types ← packages/angular-common
//   components       ← packages/angular-signal + angular-<v>/overlay (v2, v3) | angular-v1/src (v1)
//   <comp>/<comp>.css ← packages/styles
//   theme/           ← packages/themes/dist/theme   (SCSS module; _version.scss names this major's default preset)
//   themes/          ← packages/themes/dist/themes-<v> (prebuilt CSS of this major's catalog)
//   utils/           ← packages/themes/dist/utils   (utility classes: Sass module + utils.css)
//   schematics/      ← packages/schematics/dist
// Usage: node tools/sync-sources.mjs v1|v2|v3 [--as <package-name>]
//   --as renames the package and every 'wiraui/…' import inside it (docs site only: it installs
//   v1, v2 and v3 side by side, so v1's own imports must not resolve to v3).
import { cpSync, existsSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { peerRange, VERSIONS } from './versions.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = (...p) => join(root, 'packages', ...p);
const KEEP = new Set(['package.json', 'ng-package.json', 'tsconfig.lib.json']);
const SOURCES = {
  v1: [pkg('angular-v1', 'src')],
  v2: [pkg('angular-signal'), pkg('angular-v2', 'overlay')],
  v3: [pkg('angular-signal'), pkg('angular-v3', 'overlay')],
};

// Core's CJS build (pnpm build:core runs first) knows each major's presets.
const { VERSION_CATALOG } = createRequire(import.meta.url)(pkg('core', 'dist', 'cjs', 'index.js'));

const v = process.argv[2];
const spec = VERSIONS[v];
const asIndex = process.argv.indexOf('--as');
const alias = asIndex > 0 ? process.argv[asIndex + 1] : null;
if (!spec || (asIndex > 0 && !alias)) {
  console.error('usage: node tools/sync-sources.mjs v1|v2|v3 [--as <package-name>]');
  process.exit(1);
}
const lib = alias ? pkg(`angular-${v}`, 'lib-docs') : pkg(`angular-${v}`, 'lib');
const warnings = [];

if (alias) {
  // lib-docs starts as a copy of lib's three committed files, renamed and pointed at dist-docs.
  rmSync(lib, { recursive: true, force: true });
  for (const f of KEEP) cpSync(pkg(`angular-${v}`, 'lib', f), join(lib, f));
  const p = JSON.parse(readFileSync(join(lib, 'package.json'), 'utf8'));
  p.name = alias;
  delete p.schematics;
  delete p['ng-add'];
  delete p['ng-update'];
  writeFileSync(join(lib, 'package.json'), JSON.stringify(p, null, 2) + '\n');
  const ng = JSON.parse(readFileSync(join(lib, 'ng-package.json'), 'utf8'));
  ng.dest = '../dist-docs';
  writeFileSync(join(lib, 'ng-package.json'), JSON.stringify(ng, null, 2) + '\n');
}

// The committed lib/package.json must agree with tools/versions.mjs.
const libPkg = JSON.parse(readFileSync(join(lib, 'package.json'), 'utf8'));
const range = peerRange(spec);
for (const dep of ['@angular/core', '@angular/common', '@angular/forms']) {
  if (libPkg.peerDependencies[dep] !== range) {
    throw new Error(`${v}: lib/package.json peer ${dep} is "${libPkg.peerDependencies[dep]}", tools/versions.mjs says "${range}"`);
  }
}
if (!libPkg.version.startsWith(`${spec.major}.`)) throw new Error(`${v}: lib/package.json version must be ${spec.major}.x`);

for (const entry of readdirSync(lib)) if (!KEEP.has(entry)) rmSync(join(lib, entry), { recursive: true, force: true });

cpSync(pkg('core', 'src'), join(lib, 'core', 'src'), { recursive: true });
writeFileSync(join(lib, 'core', 'ng-package.json'), JSON.stringify({ lib: { entryFile: 'src/index.ts' } }, null, 2) + '\n');

for (const dir of [pkg('angular-common'), ...SOURCES[v]]) {
  if (existsSync(dir)) cpSync(dir, lib, { recursive: true });
}

// Each styles/<name>.css goes next to its component (for styleUrls) and is also written as
// <name>.styles.ts, a string constant directives load at run time (they have no template).
for (const file of readdirSync(pkg('styles'))) {
  const name = file.replace(/\.css$/, '');
  if (!existsSync(join(lib, name))) {
    warnings.push(`styles/${file} has no matching component folder`);
    continue;
  }
  const css = readFileSync(pkg('styles', file), 'utf8');
  cpSync(pkg('styles', file), join(lib, name, file));
  const constName = `WU_${name.toUpperCase()}_CSS`;
  writeFileSync(join(lib, name, `${name}.styles.ts`), `/** Generated by tools/sync-sources.mjs from packages/styles/${file}. */\nexport const ${constName} = ${JSON.stringify(css)};\n`);
}

writeFileSync(
  join(lib, 'config', 'version.ts'),
  `/** Generated by tools/sync-sources.mjs from tools/versions.mjs. */\n` +
    `export const WU_VERSION_INFO: { major: number; min: number; max: number | null } = ` +
    `{ major: ${spec.major}, min: ${spec.min}, max: ${spec.max === null ? 'null' : spec.max} };\n`
);
writeFileSync(
  join(lib, 'public-api.ts'),
  `/** wiraui@${spec.major}. Import from the entry points, e.g. 'wiraui/button', 'wiraui/config'. */\n` +
    `export const WIRAUI_MAJOR = ${spec.major};\n`
);

const copies = [
  [pkg('themes', 'dist', 'theme'), join(lib, 'theme'), 'pnpm --filter @wiraui/themes build'],
  [pkg('themes', 'dist', `themes-${v}`), join(lib, 'themes'), 'pnpm --filter @wiraui/themes build'],
  [pkg('themes', 'dist', 'utils'), join(lib, 'utils'), 'pnpm --filter @wiraui/themes build'],
  [pkg('schematics', 'dist'), join(lib, 'schematics'), 'pnpm --filter @wiraui/schematics build'],
];
for (const [from, to, fix] of copies) {
  if (alias && to.endsWith('schematics')) continue;
  if (existsSync(from)) cpSync(from, to, { recursive: true });
  else warnings.push(`${from.slice(root.length + 1)} missing (run: ${fix})`);
}

// `ng add` lists only the themes this major offers.
const THEME_LABELS = {
  mali: 'Mali: clean, modern',
  sila: 'Sila: bold, roomy',
  material: 'Material: Material Design',
  phet: 'Phet: sharp, high contrast',
  wira: "Wira: WiraUI's own look",
  lanna: 'Lanna: soft, rounded',
  siam: 'Siam: elevated, with ripple',
  nakhon: 'Nakhon: sharp, dense',
  glass: 'Glass: Liquid Glass, translucent',
};
const CLASSIC_FAMILIES = [
  [/^sila-light-/, 'Sila light'],
  [/^sila-dark-/, 'Sila dark'],
  [/^arun-/, 'Arun light'],
  [/^sayan-/, 'Sayan dim dark'],
  [/^ratri-/, 'Ratri dark'],
  [/^md-light-/, 'Material light'],
  [/^md-dark-/, 'Material dark'],
];
const schemaFile = join(lib, 'schematics', 'ng-add', 'schema.json');
if (existsSync(schemaFile)) {
  const cat = VERSION_CATALOG[spec.major];
  const label = (name) => {
    const family = CLASSIC_FAMILIES.find(([re]) => re.test(name));
    const text = THEME_LABELS[name] || `${name} · ${family ? family[1] : name}`;
    return name === cat.defaultTheme ? `${text} (default)` : text;
  };
  const schema = JSON.parse(readFileSync(schemaFile, 'utf8'));
  const theme = schema.properties.theme;
  theme.default = cat.defaultTheme;
  theme.enum = ['auto', ...cat.themes];
  theme['x-prompt'].items = [cat.defaultTheme, ...cat.themes.filter((t) => t !== cat.defaultTheme)].map((value) => ({ value, label: label(value) }));
  writeFileSync(schemaFile, JSON.stringify(schema, null, 2) + '\n');
}

// `@use 'wiraui/theme'` with no $theme / $preset gives this major's default look.
if (existsSync(join(lib, 'theme'))) {
  writeFileSync(
    join(lib, 'theme', '_version.scss'),
    `// Generated by tools/sync-sources.mjs: the preset \`@use 'wiraui/theme'\` uses when neither $theme nor $preset is set.\n` +
      `$default-preset: '${VERSION_CATALOG[spec.major].defaultPreset}';\n`
  );
}

if (alias) {
  const rewrite = (dir) => {
    for (const entry of readdirSync(dir)) {
      const file = join(dir, entry);
      if (statSync(file).isDirectory()) rewrite(file);
      else if (file.endsWith('.ts')) {
        const src = readFileSync(file, 'utf8');
        const out = src.replace(/(['"])wiraui\//g, `$1${alias}/`);
        if (out !== src) writeFileSync(file, out);
      }
    }
  };
  rewrite(lib);
}

console.log(`synced ${alias || 'wiraui'}@${spec.major} (Angular ${range}) → ${lib.slice(root.length + 1)}`);
for (const w of warnings) console.warn('  warning: ' + w);
